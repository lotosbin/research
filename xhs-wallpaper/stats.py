def classify(items, mapping):
    hits=set()
    unmatched=[]
    for it in items:
        got=False
        for theme,kws in mapping.items():
            if any(k.lower() in it.lower() for k in kws):
                hits.add(theme); got=True; break
        if not got: unmatched.append(it)
    return hits, unmatched

